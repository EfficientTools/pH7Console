fn bounded_utf8(value: &str, max_bytes: usize) -> String {
    if value.len() <= max_bytes {
        return value.to_string();
    }
    let mut end = max_bytes;
    while end > 0 && !value.is_char_boundary(end) {
        end -= 1;
    }
    value[..end].to_string()
}

fn bounded_utf8_suffix(value: &str, max_bytes: usize) -> String {
    if value.len() <= max_bytes {
        return value.to_string();
    }
    let mut start = value.len().saturating_sub(max_bytes);
    while start < value.len() && !value.is_char_boundary(start) {
        start += 1;
    }
    value[start..].to_string()
}

fn bound_untrusted_context(context: &str) -> String {
    if context.len() <= MAX_MODEL_CONTEXT_BYTES {
        return context.to_string();
    }
    let head = bounded_utf8(context, 8 * 1024);
    let tail = bounded_utf8_suffix(context, 3 * 1024);
    format!("{head}\n[... older terminal context truncated ...]\n{tail}")
}

fn contains_unsafe_display_control(value: &str) -> bool {
    value.chars().any(|character| {
        character.is_control()
            || matches!(
                character,
                '\u{061c}'
                    | '\u{200e}'
                    | '\u{200f}'
                    | '\u{2028}'..='\u{202e}'
                    | '\u{2066}'..='\u{2069}'
                    | '\u{feff}'
            )
    })
}

fn sanitize_explanation(value: &str) -> Option<String> {
    let cleaned: String = value
        .trim()
        .chars()
        .map(|character| {
            if character.is_control()
                || matches!(
                    character,
                    '\u{061c}'
                        | '\u{200e}'
                        | '\u{200f}'
                        | '\u{2028}'..='\u{202e}'
                        | '\u{2066}'..='\u{2069}'
                        | '\u{feff}'
                )
            {
                ' '
            } else {
                character
            }
        })
        .collect();
    let cleaned = bounded_utf8(cleaned.trim(), MAX_EXPLANATION_BYTES);
    (!cleaned.is_empty()).then_some(cleaned)
}

fn parse_real_command_generation(value: serde_json::Value) -> Option<CommandGeneration> {
    let command = value.get("command")?.as_str()?.trim();
    if command.is_empty()
        || command.len() > crate::shell_integration::MAX_RECORDED_COMMAND_BYTES
        || contains_unsafe_display_control(command)
    {
        return None;
    }
    let explanation = sanitize_explanation(value.get("explanation")?.as_str()?)?;
    Some(CommandGeneration {
        command: command.to_string(),
        explanation,
        confidence: 0.85,
        source: CommandGenerationSource::LocalLlm,
    })
}

fn shell_quote_literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn shell_quote_path(value: &str) -> String {
    if value == "~" {
        return "\"$HOME\"".to_string();
    }
    if let Some(relative) = value.strip_prefix("~/") {
        return format!("\"$HOME\"/{}", shell_quote_literal(relative));
    }
    shell_quote_literal(value)
}

fn deterministic_command_explanation(command: &str) -> String {
    let trimmed = command.trim_start_matches("🤖 ").trim();
    if trimmed.starts_with('#') {
        return "Deterministic local intelligence needs a more specific request before it can create a command."
            .to_string();
    }
    if trimmed.starts_with("find ") && !trimmed.contains(" -delete") && !trimmed.contains(" -exec")
    {
        return "Searches the current workspace without using a mutation flag. Review the scope before inserting it."
            .to_string();
    }
    if trimmed.starts_with("ls ") || trimmed == "ls" {
        return "Lists entries in the current directory without modifying them.".to_string();
    }
    if trimmed.starts_with("git status") || trimmed.starts_with("git diff") {
        return "Inspects the current Git workspace without changing repository state.".to_string();
    }
    if trimmed.starts_with("cd ") {
        return "Changes the current shell directory to the quoted path.".to_string();
    }
    if trimmed.starts_with("grep ") {
        return "Searches workspace text for the safely quoted literal pattern.".to_string();
    }
    "Prepared by deterministic on-device command matching. Review the command and its risk rating before inserting it."
        .to_string()
}

